"""Clean the raw CSVs and load them into a SQLite database.

Every rule is logged to reports/data_quality.md so the cleaning is auditable.
"""
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW, CLEAN, DB = ROOT / "data" / "raw", ROOT / "data" / "clean", ROOT / "data" / "store.db"
CITY_FIX = {"Jogja": "Yogyakarta", "Dki Jakarta": "Jakarta"}


def clean(raw_dir: Path = RAW):
    log = []
    products = pd.read_csv(raw_dir / "products.csv")
    customers = pd.read_csv(raw_dir / "customers.csv", parse_dates=["signup_date"])
    orders = pd.read_csv(raw_dir / "orders.csv", parse_dates=["order_ts"])
    items = pd.read_csv(raw_dir / "order_items.csv")

    # 1. city names: trim, title-case, map nicknames
    before = customers["city"].nunique()
    customers["city"] = customers["city"].str.strip().str.title().replace(CITY_FIX)
    log.append(("Customers", "Standardised city spelling (trim, title case, nicknames)",
                f"{before} distinct spellings → {customers['city'].nunique()} cities"))

    # 2. impossible prices: take the catalogue price instead
    bad = items["unit_price"] <= 0
    items.loc[bad, "unit_price"] = items.loc[bad, "product_id"].map(products.set_index("product_id")["unit_price"])
    log.append(("Order items", "Replaced non-positive unit prices with the catalogue price", f"{int(bad.sum())} rows fixed"))

    # 3. missing quantity: cannot be inferred, so drop the line
    miss = items["quantity"].isna()
    items = items[~miss].astype({"quantity": int})
    log.append(("Order items", "Dropped lines with missing quantity", f"{int(miss.sum())} rows removed"))

    # duplicates are removed after the fixes above, so a copy whose price was corrupted is caught too
    n = len(items)
    items = items.drop_duplicates()
    log.append(("Order items", "Removed exact duplicate rows (after fixing prices)", f"{n - len(items)} rows removed"))

    # orders left with no lines carry no sales; remove them
    empty = ~orders["order_id"].isin(items["order_id"])
    orders = orders[~empty]
    log.append(("Orders", "Removed orders with no remaining lines", f"{int(empty.sum())} orders removed"))

    # 4. missing payment method: keep the order, label it
    miss = orders["payment_method"].isna()
    orders["payment_method"] = orders["payment_method"].fillna("Unknown")
    log.append(("Orders", "Labelled missing payment method as 'Unknown'", f"{int(miss.sum())} orders"))

    # 5. referential integrity checks (should all be zero)
    orphan_items = (~items["order_id"].isin(orders["order_id"])).sum()
    orphan_orders = (~orders["customer_id"].isin(customers["customer_id"])).sum()
    early = (orders["order_ts"] < orders["customer_id"].map(customers.set_index("customer_id")["signup_date"])).sum()
    log.append(("Checks", "Order lines without an order / orders without a customer / orders before signup",
                f"{orphan_items} / {orphan_orders} / {early}"))

    items["net_revenue"] = (items["quantity"] * items["unit_price"] * (1 - items["discount"])).round(0)
    return {"products": products, "customers": customers, "orders": orders, "order_items": items}, log


def main():
    tables, log = clean()
    CLEAN.mkdir(parents=True, exist_ok=True)
    DB.unlink(missing_ok=True)
    with sqlite3.connect(DB) as conn:
        for name, df in tables.items():
            df.to_csv(CLEAN / f"{name}.csv", index=False)
            df.to_sql(name, conn, index=False)
    lines = ["# Data Quality Log", "", "Generated by `scripts/clean.py`.", "",
             "| Table | Rule | Result |", "|---|---|---|"] + [f"| {t} | {r} | {x} |" for t, r, x in log]
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "data_quality.md").write_text("\n".join(lines) + "\n")
    print("\n".join(f"{t}: {r} -> {x}" for t, r, x in log))


if __name__ == "__main__":
    main()
